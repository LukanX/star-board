import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = process.argv[process.argv.indexOf("--output") + 1];
if (!process.argv.includes("--output") || !output) throw new Error("Choose --output <new forward migration path>.");
const ancestry = JSON.parse(await readFile(path.join(root, "lib", "references", "catalog.generated.json"), "utf8"));
const traits = JSON.parse(await readFile(path.join(root, "lib", "references", "creature-traits.generated.json"), "utf8"));
const quote = (text) => `'${text.replaceAll("'", "''")}'`;
const rows = [ancestry, traits].flatMap((catalog) => catalog.records.filter((record) => record.kind !== "class").map((record) =>
  [record.id, record.kind, record.name, catalog.catalogVersion, record.sourceUrl, record.publication ?? ""].map(quote).join(", "),
));
await writeFile(path.resolve(root, output), `-- Generated by scripts/seed-system-references.mjs. Metadata only; authored fields start empty.\ninsert into public.system_reference_entries(reference_id, kind, name, catalog_version, source_url, publication) values\n${rows.map((row) => `  (${row})`).join(",\n")}\non conflict (reference_id) do update set name = excluded.name, catalog_version = excluded.catalog_version, source_url = excluded.source_url, publication = excluded.publication;\n`, { flag: "wx" });
console.info(`Wrote ${rows.length} metadata entries. Revisions are not modified.`);
